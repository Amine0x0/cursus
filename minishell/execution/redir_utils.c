#include "../mini.h"

void	apply_heredocs(t_heredoc *hd)
{
	while (hd)
	{
		if (hd->fd != -1)
		{
			dup2(hd->fd, STDIN_FILENO);
			close(hd->fd);
		}
		hd = hd->next;
	}
}
